import { readFileSync } from 'node:fs';

/*
 * Reads assets/rocketwave-logo.svg and turns it into logo-paths.ts, so the Logo component
 * draws the exact paths of the official file. Each path is tagged by its colour in the file:
 * #EB6700 is the rocket, #FF9900 the flame, black the wordmark.
 */

import type { LogoPart } from './logo-types';

const PART_BY_FILL: Record<string, LogoPart['part']> = {
  '#EB6700': 'rocket',
  '#FF9900': 'flame',
  black: 'wordmark',
  '#000000': 'wordmark',
};

export function readLogo(): { viewBox: string; parts: LogoPart[] } {
  const svg = readFileSync(new URL('../../assets/rocketwave-logo.svg', import.meta.url), 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (!viewBox) throw new Error('Logo SVG has no viewBox');

  const parts: LogoPart[] = [];
  for (const match of svg.matchAll(/<path\s+d="([^"]+)"\s+fill="([^"]+)"\s*\/>/g)) {
    const [, d, fill] = match;
    const part = PART_BY_FILL[fill ?? ''];
    if (!d || !part) throw new Error(`Logo path with unexpected fill "${fill}"`);
    parts.push({ part, d });
  }
  if (parts.length === 0) throw new Error('Logo SVG has no paths');
  return { viewBox, parts };
}

export function renderLogoModule(): string {
  const { viewBox, parts } = readLogo();
  return [
    '// GENERATED by packages/ui/src/tokens/logo-source.ts from assets/rocketwave-logo.svg: do not edit by hand.',
    "import type { LogoPart } from '../tokens/logo-types';",
    '',
    `export const logoViewBox = ${JSON.stringify(viewBox)};`,
    '',
    `export const logoParts: readonly LogoPart[] = ${JSON.stringify(parts, null, 2)};`,
    '',
  ].join('\n');
}
